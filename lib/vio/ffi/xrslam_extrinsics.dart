// 为什么这个文件必须存在:
//   在此之前我们给 cam0.extrinsic 填的是**单位四元数**,而真值是一个 180°
//   翻转。相机-IMU 朝向整个错了 ⇒ 视觉-惯性对齐永远收敛不了。真机实测:
//   连续喂 5731 帧 / 17447 个 IMU 样本,前端跟踪正常(89 个点稳定跟住),
//   但 slamState 一直是 0、一个位姿都没出。
//   我当时在代码注释里写的是"iOS 无任何 API 提供相机-IMU 外参 —— 真缺口",
//   而答案就躺在我正在复刻的那个上游仓库里。
//
// 🔑 旋转与平移的性质完全不同,这决定了"逐机型标定"是不是阻断:
//
//   q_bc  18/18 机型**完全相同**(iPhone X 2017 → iPhone 16e 2025,跨 8 年)
//         ⇒ 它是坐标系约定,不是标定量。可泛化,零逐机型工作。
//         填错的代价是灾难性的(整个朝向错)。
//
//   p_bc  18 个机型 17 个不同值。x∈[0.26,53.62]mm y∈[-26.04,94.24]mm
//         z∈[-14.63,15.08]mm ⇒ 逐机型。
//         填错的代价是厘米级杠杆臂,有界且远小于朝向错误。
//
//   所以未知机型回退到分量中位数是可接受的:代价是几厘米杠杆臂,
//   而不是 180° 全错。这条正是"国行机型逐个实测不可能"能成立的原因。
//
// ⚠️ 上游自己在 iPhone 16e 上直接复用了 iPhone 14 Pro 的 p_bc(两者逐位相同),
//    说明这张表里至少有一项不是真标定值。照抄,但记在这里。

